import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";

const [runtimeSource, capabilitySource, platformRuntimeSource] = await Promise.all([
  readFile("lib/operator/runtime/OperatorOrganizationalContextRuntime.js", "utf8"),
  readFile("lib/platform/capabilities/createOperatorOrganizationalContextCapability.js", "utf8"),
  readFile("lib/platform/runtime/PlatformDomainRuntime.js", "utf8"),
]);

assert.match(runtimeSource, /from\("organizations"\)/);
assert.match(runtimeSource, /from\("organization_industries"\)/);
assert.match(runtimeSource, /from\("ai_business_profiles"\)/);
assert.match(runtimeSource, /from\("intelligence_conversations"\)/);
assert.match(runtimeSource, /from\("intelligence_turns"\)/);
assert.match(runtimeSource, /\.eq\("organization_id", organizationId\)/);
assert.ok(
  (runtimeSource.match(/\.eq\("party_id", partyId\)/g) || []).length >= 2,
  "prior goals and execution history must both remain same-party scoped",
);
assert.match(runtimeSource, /relevant_prior_goals/);
assert.match(runtimeSource, /relevant_verified_history/);
assert.match(runtimeSource, /STATIC_TTL_MS = 5 \* 60 \* 1000/);
assert.doesNotMatch(
  runtimeSource,
  /restaurant|hotel|construction|healthcare|pest_control|retail|entertainment|accounting_firm/i,
);
assert.doesNotMatch(runtimeSource, /buildDefaultBusinessProfile|getOrCreateBusinessProfile/);

assert.match(capabilitySource, /capability: "organizational_context"/);
assert.match(capabilitySource, /action: "read"/);
assert.match(capabilitySource, /operatorMode: "read"/);
assert.match(capabilitySource, /operatorAutoExecute: true/);
assert.match(capabilitySource, /operatorRequiresConfirmation: false/);
assert.match(capabilitySource, /contextScope: "organization"/);
assert.match(capabilitySource, /context\?\.metadata\?\.partyId/);
assert.match(capabilitySource, /loadOperatorOrganizationalContext/);
assert.match(
  capabilitySource,
  /No fallback profile is generated by this capability/i,
);

assert.match(
  platformRuntimeSource,
  /createOperatorOrganizationalContextCapability/,
);
assert.match(platformRuntimeSource, /organizational_context:\s*\{/);
assert.match(
  platformRuntimeSource,
  /read:\s*async \(\) => createOperatorOrganizationalContextCapability\(\)/,
);

